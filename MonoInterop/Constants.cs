    public static bool CutMethod(MethodDefinition Method) //global method cutter
    {
        if (Method.DeclaringType.MetadataType == MetadataType.String && Method.IsConstructor)
        {
            return true;
        }

        if (Method.DeclaringType.IsPrimitive() && Method.Name.StartsWith("op"))
        {
            return true;
        }
        return false;
    }
